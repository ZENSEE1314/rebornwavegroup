import pg from "pg";
const BASE = "http://127.0.0.1:3999";
let failures = 0;
const check = (name, ok, extra = "") => { console.log((ok ? "PASS " : "FAIL ") + name + (ok ? "" : "  → " + extra)); if (!ok) failures++; };
let cookie = "";
const call = async (method, path, body) => {
  const res = await fetch(BASE + path, { method, headers: { "Content-Type": "application/json", ...(cookie ? { cookie } : {}) }, body: body ? JSON.stringify(body) : undefined, redirect: "manual" });
  const set = res.headers.getSetCookie?.() || []; if (set.length) cookie = set.map((c) => c.split(";")[0]).join("; ");
  return { status: res.status, text: await res.text(), type: res.headers.get("content-type"), disp: res.headers.get("content-disposition") };
};
const bridge = await call("GET", "/api/karaoke/bridge.mjs");
check("the bridge program can be fetched without logging in", bridge.status === 200 && /findBox/.test(bridge.text) && /javascript/.test(bridge.type || ""), `${bridge.status} ${bridge.type}`);
check("the program itself holds no token", !/KARAOKE_TOKEN=[A-Z0-9]{8}/.test(bridge.text));
let r = await call("GET", "/api/reborn/admin/karaoke/setup-file");
check("the setup file needs an admin", r.status === 401 || r.status === 403, r.status);
await call("POST", "/api/auth/login", { email: "admin@test.local", password: "Passw0rd!" });
r = await call("GET", "/api/reborn/admin/karaoke/setup-file");
check("the admin downloads a .bat file", r.status === 200 && /Start-Karaoke-Bridge\.bat/.test(r.disp || ""), `${r.status} ${r.disp}`);
const token = /set KARAOKE_TOKEN=(\S+)/.exec(r.text)?.[1];
check("it holds this server's address and a token", /set CLOUD_URL=http:\/\/127\.0\.0\.1:3999/.test(r.text) && !!token && token.length >= 8, r.text.slice(0, 300));
const db = new pg.Client({ connectionString: "postgres://postgres:pw@127.0.0.1:54329/reborn" }); await db.connect();
const saved = (await db.query("SELECT value FROM app_settings WHERE key='karaokeToken'")).rows[0]?.value;
check("the token in the file is the one the server accepts", saved === token, `${saved} vs ${token}`);
const again = await call("GET", "/api/reborn/admin/karaoke/setup-file");
check("downloading again keeps the same token (the running bridge is not cut off)", /set KARAOKE_TOKEN=(\S+)/.exec(again.text)?.[1] === token);
const q = await fetch(BASE + "/api/karaoke/queue", { headers: { "x-karaoke-token": token } });
check("that token works for the bridge", q.status === 200, q.status);
await db.end();
console.log(failures ? `${failures} FAILED` : "ALL PASSED"); process.exit(failures ? 1 : 0);
