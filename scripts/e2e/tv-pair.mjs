const BASE = "http://127.0.0.1:3999";
let failures = 0;
const check = (name, ok, extra = "") => { console.log((ok ? "PASS " : "FAIL ") + name + (ok ? "" : "  → " + extra)); if (!ok) failures++; };
let cookie = "";
const call = async (method, path, body) => {
  const res = await fetch(BASE + path, { method, headers: { "Content-Type": "application/json", ...(cookie ? { cookie } : {}) }, body: body ? JSON.stringify(body) : undefined });
  const set = res.headers.getSetCookie?.() || []; if (set.length) cookie = set.map((c) => c.split(";")[0]).join("; ");
  const text = await res.text(); let json = null; try { json = JSON.parse(text); } catch { /* html */ }
  return { status: res.status, json, text };
};
let r = await call("POST", "/api/tv/pair");
const code = r.json?.code;
check("a waiting TV gets a 6-digit code without logging in", r.status === 200 && /^[0-9]{6}$/.test(code), JSON.stringify(r.json));
r = await call("GET", `/api/tv/pair/${code}`);
check("the TV keeps waiting until it is linked", r.json?.status === "waiting", JSON.stringify(r.json));
await call("POST", "/api/auth/login", { email: "admin@test.local", password: "Passw0rd!" });
let tv = (await call("PUT", "/api/reborn/admin/tv", { screens: [{ id: "", name: "Bar TV", view: "overlay", tables: [] }, { id: "", name: "Stage TV", view: "queue", tables: [] }] })).json;
const screen = tv.screens.find((s) => s.name === "Stage TV");
check("the admin has TV screens with their own addresses", tv.screens.length >= 2 && !!screen?.token, JSON.stringify(tv).slice(0, 200));
r = await call("POST", "/api/reborn/admin/tv/pair", { code: "000000", screenId: screen.id });
check("a code that is on no TV is refused", r.status === 404, r.status);
r = await call("POST", "/api/reborn/admin/tv/pair", { code: "12", screenId: screen.id });
check("a code that is not 6 digits is refused", r.status === 400, r.status);
r = await call("POST", "/api/reborn/admin/tv/pair", { code, screenId: "nope" });
check("a TV screen that does not exist is refused", r.status === 404, r.status);
r = await call("POST", "/api/reborn/admin/tv/pair", { code: code.slice(0, 3) + " " + code.slice(3), screenId: screen.id });
check("the admin links the code (a space in it does not matter)", r.status === 200, JSON.stringify(r.json));
r = await call("GET", `/api/tv/pair/${code}`);
check("the TV is sent to its own screen's page", r.json?.status === "linked" && r.json.path === `/tv/${screen.token}`, JSON.stringify(r.json));
r = await call("GET", `/api/tv/pair/${code}`);
check("the code is used up after that", r.json?.status === "expired", JSON.stringify(r.json));
const state = await call("GET", `/api/tv/${screen.token}/state`);
check("the page it was sent to works", state.status === 200 && state.json?.name === "Stage TV", `${state.status} ${state.text.slice(0, 100)}`);
const page = await call("GET", "/tv");
check("the short address /tv serves the app page", page.status === 200 && /<div id="root"/.test(page.text), page.status);
cookie = "";
r = await call("POST", "/api/reborn/admin/tv/pair", { code, screenId: screen.id });
check("linking needs an admin", r.status === 401 || r.status === 403, r.status);
console.log(failures ? `${failures} FAILED` : "ALL PASSED"); process.exit(failures ? 1 : 0);
